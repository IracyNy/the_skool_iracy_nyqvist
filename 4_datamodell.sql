-- UPPGIFT 4 (BONUS): Implementera datamodell

-- 1. Skapa tabell för utbildningsområden
DROP TABLE ansokan;
DROP TABLE utbildningsanordnare;
DROP TABLE utbildningsomrade;

CREATE TABLE utbildningsomrade (
    utbildningsomrade_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utbildningsomrade_namn VARCHAR2(128) NOT NULL
);

-- 2. Skapa tabell för utbildningsanordnare
CREATE TABLE utbildningsanordnare (
    anordnare_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anordnare_namn VARCHAR2(128) NOT NULL,
    huvudmannatyp VARCHAR2(26)
);

-- 3. Skapa tabell för ansökningar
CREATE TABLE ansokan (
    ansokan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utbildningsomrade_id NUMBER,
    anordnare_id NUMBER,
    utbildningsnamn VARCHAR2(128),
    beslut VARCHAR2(26),
    lan VARCHAR2(26),
    kommun VARCHAR2(26),
    yh_poang NUMBER(5),
    studieform VARCHAR2(26),
    CONSTRAINT fk_omrade FOREIGN KEY (utbildningsomrade_id) REFERENCES utbildningsomrade(utbildningsomrade_id),
    CONSTRAINT fk_anordnare FOREIGN KEY (anordnare_id) REFERENCES utbildningsanordnare(anordnare_id)
);

-- 4. Fyll utbildningsomrade med unika värden från ansokningar
INSERT INTO utbildningsomrade (utbildningsomrade_namn)
SELECT DISTINCT utbildningsomrade FROM ansokningar;

-- 5. Fyll utbildningsanordnare med unika värden från ansokningar
INSERT INTO utbildningsanordnare (anordnare_namn, huvudmannatyp)
SELECT DISTINCT utbildningsanordnare_administr, huvudmannatyp FROM ansokningar;

-- 6. Fyll ansokan med data (koppla ihop med ID:n)
INSERT INTO ansokan (utbildningsomrade_id, anordnare_id, utbildningsnamn, beslut, lan, kommun, yh_poang, studieform)
SELECT
    u.utbildningsomrade_id,
    a.anordnare_id,
    ans.utbildningsnamn,
    ans.beslut,
    ans.lan,
    ans.kommun,
    ans.YH_POANG,
    ans.studieform
FROM ansokningar ans
JOIN utbildningsomrade u ON ans.utbildningsomrade = u.utbildningsomrade_namn
JOIN utbildningsanordnare a ON ans.utbildningsanordnare_administr = a.anordnare_namn AND ans.huvudmannatyp = a.huvudmannatyp;

COMMIT;

-- 7. Verifiera datamodellen
SELECT COUNT(*) AS antal_omraden FROM utbildningsomrade;
SELECT COUNT(*) AS antal_anordnare FROM utbildningsanordnare;
SELECT COUNT(*) AS antal_ansokningar FROM ansokan;

-- 8. Testa en join (samma som fråga 1 i Uppgift 1, men med nya tabeller)
SELECT u.utbildningsomrade_namn, COUNT(*) AS antal_ansokningar
FROM ansokan ans
JOIN utbildningsomrade u ON ans.utbildningsomrade_id = u.utbildningsomrade_id
GROUP BY u.utbildningsomrade_namn
ORDER BY antal_ansokningar DESC;

EXIT;

